"""Rebuild the built-in fallback PE image used by gt().

The generated 1024-byte x64 DLL is original work of this project: it exports
nothing, its entry point simply returns TRUE, and it has no side effects.
It exists only so that a missing *.dll request still yields a loadable image
instead of crashing the caller. It is NOT the upstream native module.

Outputs (relative to this script):
    ../payload/DebugNative.stub.dll   reference copy
    ../src/StubDll.java               Base64 constant used at runtime

On Windows the DLL is also load-tested with LoadLibraryW.
"""
import base64
import ctypes
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAYLOAD = os.path.join(ROOT, "payload")
SRC = os.path.join(ROOT, "src")


def build_dll():
    dos = bytearray(0x80)
    dos[0:2] = b"MZ"
    struct.pack_into("<I", dos, 0x3C, 0x80)

    pe = bytearray(b"PE\0\0")
    pe += struct.pack("<HHIIIHH", 0x8664, 1, 0, 0, 0, 0xF0, 0x2022)

    opt = bytearray(0xF0)
    struct.pack_into("<H", opt, 0, 0x20B)          # PE32+
    struct.pack_into("<I", opt, 4, 0x200)           # SizeOfCode
    struct.pack_into("<I", opt, 16, 0x1000)         # AddressOfEntryPoint
    struct.pack_into("<I", opt, 20, 0x1000)         # BaseOfCode
    struct.pack_into("<Q", opt, 24, 0x180000000)    # ImageBase
    struct.pack_into("<I", opt, 32, 0x1000)         # SectionAlignment
    struct.pack_into("<I", opt, 36, 0x200)          # FileAlignment
    struct.pack_into("<HH", opt, 40, 6, 0)
    struct.pack_into("<HH", opt, 48, 6, 0)
    struct.pack_into("<I", opt, 56, 0x2000)         # SizeOfImage
    struct.pack_into("<I", opt, 60, 0x200)          # SizeOfHeaders
    struct.pack_into("<H", opt, 68, 3)              # Subsystem = CUI
    struct.pack_into("<Q", opt, 72, 0x100000)
    struct.pack_into("<Q", opt, 80, 0x1000)
    struct.pack_into("<Q", opt, 88, 0x100000)
    struct.pack_into("<Q", opt, 96, 0x1000)
    struct.pack_into("<I", opt, 108, 16)            # NumberOfRvaAndSizes
    pe += opt

    sec = bytearray(40)
    sec[0:8] = b".text\0\0\0"
    struct.pack_into("<I", sec, 8, 0x10)
    struct.pack_into("<I", sec, 12, 0x1000)
    struct.pack_into("<I", sec, 16, 0x200)
    struct.pack_into("<I", sec, 20, 0x200)
    struct.pack_into("<I", sec, 36, 0x60000020)     # CODE|EXECUTE|READ
    pe += sec

    headers = (bytes(dos) + bytes(pe)).ljust(0x200, b"\0")
    code = b"\xB8\x01\x00\x00\x00\xC3"              # mov eax,1; ret
    return headers + code.ljust(0x200, b"\0")


JAVA_TEMPLATE = """// SPDX-License-Identifier: MIT
// Co-creator: momofile
import java.util.Base64;

/** Built-in, side-effect-free fallback PE image returned by gt() for missing DLLs.
 *  Generated by tools/make_stub_dll.py; this file is original work of this project. */
public final class StubDll {
    private static final String B64 = "%s";
    private StubDll() {}
    public static byte[] bytes() {
        return Base64.getDecoder().decode(B64);
    }
}
"""


def main():
    os.makedirs(PAYLOAD, exist_ok=True)
    blob = build_dll()
    path = os.path.join(PAYLOAD, "DebugNative.stub.dll")
    with open(path, "wb") as f:
        f.write(blob)
    print("wrote %s (%d bytes)" % (path, len(blob)))

    if os.name == "nt":
        k32 = ctypes.windll.kernel32
        k32.LoadLibraryW.argtypes = [ctypes.c_wchar_p]
        k32.LoadLibraryW.restype = ctypes.c_void_p
        h = k32.LoadLibraryW(path)
        if h:
            k32.FreeLibrary.argtypes = [ctypes.c_void_p]
            k32.FreeLibrary(h)
            print("LoadLibraryW: stub DLL loads OK")
        else:
            print("WARNING: stub DLL failed to load")

    b64 = base64.b64encode(blob).decode("ascii")
    with open(os.path.join(SRC, "StubDll.java"), "w", encoding="utf-8") as f:
        f.write(JAVA_TEMPLATE % b64)
    print("wrote src/StubDll.java")


if __name__ == "__main__":
    main()
